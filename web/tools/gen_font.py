def build():
    font = bytearray(2048)
    lines = [l for l in ART.split('\n') if l != '']
    i = 0
    while i < len(lines):
        ch = lines[i]; rows = lines[i+1:i+9]; i += 9
        assert len(ch) == 1 and len(rows) == 8 and all(len(r) == 5 for r in rows), (ch, rows)
        c = ord(ch)
        for y, r in enumerate(rows):
            b = 0
            for x, p in enumerate(r):
                if p == '#': b |= 0x80 >> (x + 1)
            font[c * 8 + y] = b
    for y in range(8): font[219 * 8 + y] = 0xFF
    # control characters the game can echo (Ctrl+letter, Esc, Delete): arrows for 24..27, a hollow
    # box for the rest -- own 5x7 designs in the style of the printable glyphs
    BOX = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####', '.....']
    EXTRA = {
        24: ['..#..', '.###.', '#.#.#', '..#..', '..#..', '..#..', '..#..', '.....'],
        25: ['..#..', '..#..', '..#..', '..#..', '#.#.#', '.###.', '..#..', '.....'],
        26: ['.....', '..#..', '...#.', '#####', '...#.', '..#..', '.....', '.....'],
        27: ['.....', '..#..', '.#...', '#####', '.#...', '..#..', '.....', '.....'],
    }
    for c in list(range(1, 32)) + [127]:
        for y, r in enumerate(EXTRA.get(c, BOX)):
            b = 0
            for x, px in enumerate(r):
                if px == '#': b |= 0x80 >> (x + 1)
            font[c * 8 + y] = b
    return font
if __name__ == '__main__':
    f = build()
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'font.js')
    with open(out, 'w') as o:
        o.write('// Original 8x8 font for the Monopoly web port (5x7 dot-matrix style, own design).\n')
        o.write('// 256 glyphs x 8 rows, MSB = leftmost pixel. ASCII 1..127 (control characters as arrows/boxes) and 219.\n')
        o.write('export const BUILTIN_FONT = new Uint8Array([\n')
        for g in range(256):
            o.write('  ' + ','.join('0x%02x' % b for b in f[g*8:g*8+8]) + ',\n')
        o.write(']);\n')
    print('ok')
